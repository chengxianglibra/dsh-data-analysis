import { createHash } from 'node:crypto'
import { lstat, mkdtemp, readdir, readFile, rename, rm, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const packageRoot = fileURLToPath(new URL('../', import.meta.url))

/** Generate the expected identity before compiling either a source or package build. */
export async function generateSkillBuild() {
  const manifest = JSON.parse(await readFile(path.join(packageRoot, 'package.json'), 'utf8'))
  /** @type {Array<{path: string, sha256: string}>} */
  const files = []
  /** @param {string} relative */
  async function visit(relative) {
    const filename = path.join(packageRoot, 'skills', relative)
    const info = await lstat(filename)
    if (info.isDirectory()) {
      for (const child of (await readdir(filename)).sort()) await visit(`${relative}/${child}`)
    } else if (info.isFile()) {
      files.push({
        path: relative,
        sha256: createHash('sha256')
          .update(await readFile(filename))
          .digest('hex'),
      })
    } else {
      throw new Error(`Packaged Skill resource must be a regular file or directory: ${relative}`)
    }
  }
  if (!Array.isArray(manifest.files)) throw new Error('Package files must be an array')
  /** @type {string[]} */
  const roots = []
  for (const entry of manifest.files) {
    if (typeof entry !== 'string') throw new Error('Package files entries must be strings')
    if (!entry.startsWith('skills/')) continue
    const match = /^skills\/([^/]+)\/\*\*$/.exec(entry)
    if (!match?.[1]) throw new Error(`Unsupported packaged Skill files entry: ${entry}`)
    roots.push(match[1])
  }
  roots.sort()
  if (roots.length === 0) throw new Error('No packaged Skills declared')
  for (const root of roots) {
    await visit(root)
    if (!files.some((file) => file.path === `${root}/SKILL.md`))
      throw new Error(`Packaged Skill is missing ${root}/SKILL.md`)
  }
  const build = {
    schema: 'dsh-data-analysis-skills/v1',
    digest: createHash('sha256').update(JSON.stringify(files)).digest('hex'),
    files,
  }
  const temporary = await mkdtemp(path.join(packageRoot, '.skill-build-'))
  try {
    const filename = path.join(temporary, 'skill-build.generated.ts')
    await writeFile(
      filename,
      '// Generated by scripts/generate-skill-build.mjs; do not edit.\n' +
        "import type { PackagedSkillBuild } from './skill-build.ts'\n" +
        `export const packagedSkillBuild: PackagedSkillBuild = ${JSON.stringify(build, null, 2)}\n`,
    )
    await rename(filename, path.join(packageRoot, 'src/skill-build.generated.ts'))
  } finally {
    await rm(temporary, { recursive: true, force: true })
  }
  return { digest: build.digest, files: files.length }
}

if (process.argv[1] === fileURLToPath(import.meta.url))
  console.log(JSON.stringify(await generateSkillBuild()))
