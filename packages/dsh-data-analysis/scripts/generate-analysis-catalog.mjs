import { createHash } from 'node:crypto'
import { mkdtemp, readFile, rename, rm, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { build } from 'esbuild'
import { buildUIStyles } from './build-ui-styles.mjs'

const root = fileURLToPath(new URL('../', import.meta.url))
const require = createRequire(path.join(root, 'package.json'))

/** @param {'build' | 'check' | 'update'} mode */
export async function buildAnalysisCatalog(mode = 'build') {
  process.env.OPENUI_TELEMETRY_DISABLED = '1'
  process.env.DO_NOT_TRACK = '1'
  await buildUIStyles()
  const directory = await mkdtemp(path.join(root, '.analysis-catalog-'))
  try {
    const filename = path.join(directory, 'library.mjs')
    await build({
      entryPoints: [path.join(root, 'src/client/analysis-ui/library.tsx')],
      outfile: filename,
      bundle: true,
      packages: 'external',
      platform: 'node',
      format: 'esm',
      jsx: 'automatic',
    })
    const { analysisLibrary, analysisCatalogId, analysisRootComponents } = await import(
      pathToFileURL(filename).href
    )
    const manifest = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'))
    const versions = Object.fromEntries(
      await Promise.all(
        Object.entries(manifest.dependencies)
          .filter(([name]) => name.startsWith('@openuidev/'))
          .sort()
          .map(async ([name, pinned]) => {
            const entry = require.resolve(name)
            let owner = path.dirname(entry)
            while (path.basename(owner) !== name.split('/').at(-1)) owner = path.dirname(owner)
            const installed = JSON.parse(await readFile(path.join(owner, 'package.json'), 'utf8'))
            if (installed.version !== pinned) throw new Error(`Install pinned ${name}@${pinned}`)
            return [name, installed.version]
          }),
      ),
    )
    const data = {
      id: analysisCatalogId,
      roots: analysisRootComponents,
      versions,
      spec: analysisLibrary.toSpec(),
      schema: analysisLibrary.toJSONSchema(),
    }
    const digest = createHash('sha256').update(JSON.stringify(data)).digest('hex')
    const source = [
      '// Generated by scripts/generate-analysis-catalog.mjs. Host data only; do not edit.',
      "import type { LibraryJSONSchema, LibrarySpec } from '@openuidev/lang-core'",
      `export const analysisCatalogId = ${JSON.stringify(data.id)}`,
      `export const analysisCatalogBuild = ${JSON.stringify(digest)}`,
      `export const analysisCatalogVersions = ${JSON.stringify(versions, null, 2)}`,
      `export const analysisRootComponents = ${JSON.stringify(data.roots)}`,
      `const specData = ${JSON.stringify(data.spec, null, 2)}`,
      `export const analysisCatalogSpec: LibrarySpec = specData`,
      `const schemaData = ${JSON.stringify(data.schema, null, 2)}`,
      `export const analysisCatalogSchema: LibraryJSONSchema = schemaData`,
      '',
    ].join('\n')
    // Use the repository CLI, rather than a separate formatting dependency.
    const { execFileSync } = await import('node:child_process')
    const formatted = execFileSync(
      require.resolve('@biomejs/biome/bin/biome'),
      ['format', '--stdin-file-path=analysis-catalog.ts'],
      { input: source, encoding: 'utf8' },
    )
    const output = path.join(root, 'src/presentation/contracts/analysis-catalog.ts')
    const signaturesPath = path.join(
      root,
      'skills/dsh-data-analysis-presentation/references/analysis-catalog.md',
    )
    const signatures =
      '# 静态分析 UI 组件签名\n\n<!-- Generated by generate-analysis-catalog.mjs; do not edit. -->\n\n' +
      Object.entries(data.spec.components)
        .map(([name, c]) => `## ${name}\n\n\`\`\`text\n${c.signature}\n\`\`\`\n`)
        .join('\n') +
      '\nImage.src 是已准入的 image-file 资源名。DatasetView 支持 auto/table/metric/line/area/bar/heatmap；图表 encoding 显式引用列 ID，按保存行首次出现的顺序展示，不聚合、不推断分析语义。metric 必须为完整单行结果，Dataset 图表要求完整快照。AnalysisFrameView 按已捕获的 Frame 结构与语义解析视图。\n'
    if (mode === 'update') await writeFile(signaturesPath, signatures)
    else if ((await readFile(signaturesPath, 'utf8')) !== signatures)
      throw new Error('Analysis signatures are stale')

    if (mode === 'check') {
      if ((await readFile(output, 'utf8')) !== formatted)
        throw new Error('Analysis Catalog is stale')
    } else {
      const temporary = path.join(directory, 'analysis-catalog.ts')
      await writeFile(temporary, formatted)
      await rename(temporary, output)
    }
    return { id: data.id, build: digest, components: Object.keys(data.spec.components) }
  } finally {
    await rm(directory, { recursive: true, force: true })
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const result = await buildAnalysisCatalog(
    process.argv.includes('--check')
      ? 'check'
      : process.argv.includes('--build')
        ? 'build'
        : 'update',
  )
  console.log(JSON.stringify(result))
}
