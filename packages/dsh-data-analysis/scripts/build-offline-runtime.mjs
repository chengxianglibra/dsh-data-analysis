import { mkdtemp, rename, rm, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'
import { noticeComment, thirdPartyNotices } from './presentation-build/shared.mjs'

const root = fileURLToPath(new URL('../', import.meta.url))

/** Build a complete browser runtime, including React, for offline file:// use. */
export async function buildOfflineRuntime() {
  const result = await build({
    entryPoints: [path.join(root, 'src/client/analysis-ui/offline-runtime.tsx')],
    bundle: true,
    write: false,
    metafile: true,
    platform: 'browser',
    format: 'iife',
    target: 'es2022',
    jsx: 'automatic',
    define: { 'process.env.NODE_ENV': '"production"' },
    minify: true,
    legalComments: 'eof',
  })
  for (const [input] of Object.entries(result.metafile.inputs)) {
    if (/(?:^|\/)node_modules\/@deepseek-ai\//.test(input.replaceAll('\\', '/')))
      throw new Error(`host-module-in-offline-runtime:${input}`)
  }
  if (Object.values(result.metafile.outputs).some((output) => output.imports.length))
    throw new Error('external-import-in-offline-runtime')
  if (result.outputFiles.length !== 1) throw new Error('unexpected-offline-runtime-output')
  const output = result.outputFiles[0]
  if (!output) throw new Error('missing-offline-runtime-output')
  const code = noticeComment(await thirdPartyNotices(result.metafile)) + output.text
  const source = `// Generated by scripts/build-offline-runtime.mjs. Do not edit.\nexport const OFFLINE_RUNTIME: string = ${JSON.stringify(code)}\n`
  const directory = await mkdtemp(path.join(root, '.offline-runtime-'))
  try {
    const temporary = path.join(directory, 'runtime.ts')
    await writeFile(temporary, source)
    await rename(temporary, path.join(root, 'src/client/analysis-ui/offline-runtime.generated.ts'))
  } finally {
    await rm(directory, { recursive: true, force: true })
  }
}
